#!/usr/bin/env bash
# Installs the Reels Studio dashboard into ComfyUI (served at /reels). Run once, then restart the pod.
set -euo pipefail
COMFY="${COMFY_DIR:-}"
if [ -z "$COMFY" ]; then
  for d in /workspace/runpod-slim/ComfyUI /workspace/ComfyUI /ComfyUI /root/ComfyUI; do
    [ -f "$d/main.py" ] && COMFY="$d" && break
  done
fi
[ -n "$COMFY" ] || { echo "ComfyUI not found. Run with COMFY_DIR=/path/to/ComfyUI"; exit 1; }
DEST="$COMFY/custom_nodes/ComfyUI-ReelsStudio"
mkdir -p "$DEST"
sed -n '/^__PAYLOAD__$/,$p' "$0" | tail -n +2 | base64 -d | tar -xz -C "$DEST"
echo "Reels Studio installed in $DEST"
[ -n "${RUNPOD_POD_ID:-}" ] && echo "After restarting the pod, open: https://${RUNPOD_POD_ID}-8188.proxy.runpod.net/reels"
exit 0
